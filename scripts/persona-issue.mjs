import { execFileSync } from 'node:child_process';
import { mkdir, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import crypto from 'node:crypto';

const LABEL = 'persona-anomaly';
const MARKER_PREFIX = '<!-- flight-persona-anomaly: ';

export function buildSignature(report) {
  const keys = new Set();
  for (const a of report.anomalies ?? []) keys.add(`${a.code}:${a.severity}`);
  const flight = report.flight ?? {};
  return crypto.createHash('sha1')
    .update([...keys].sort().join('|') + ':' + flight.aircraft + ':' + flight.airport + ':' + flight.scenario)
    .digest('hex').slice(0, 12);
}

export function formatIssue(report, { commit, repo }) {
  const seen = new Map();
  for (const a of report.anomalies ?? []) seen.set(`${a.code}|${a.value}|${a.message}`, a);
  const signature = buildSignature(report);
  const f = report.flight ?? {};
  const flightLine = [f.aircraft, f.airport, f.scenario].filter(Boolean).join(' @ ') || 'unknown';
  const lines = [
    '## Flight Persona anomaly report',
    '',
    '- Persona: `flight-persona` v1',
    `- Detected: ${report.timestamp}`,
    `- Commit: \`${commit}\``,
    `- Repo: ${repo ?? 'unknown'}`,
    `- Scenario: ${flightLine}`,
    `- Duration: ${Number.isFinite(f.durationSec) ? f.durationSec.toFixed(1) + ' s' : 'unknown'}`,
    `- Peak values: G=${f.peakG ?? 'n/a'}, IAS=${f.peakIas ?? 'n/a'} kt, alt=${f.peakAltitudeFt ?? 'n/a'} ft`,
    `- Crash: ${f.crash ? JSON.stringify(f.crash) : 'none'}`,
    '',
    `### Anomalies (${report.anomalies?.length ?? 0} samples, ${seen.size} distinct)`,
    '',
  ];
  for (const a of seen.values()) {
    lines.push(`- **${a.code}** (${a.severity}) — ${a.message}`);
    if (a.value != null) lines.push(`  - value: \`${a.value}\``);
    lines.push(`  - source: ${a.source ?? 'persona'}${a.tick != null ? `, tick ${a.tick}` : ''}`);
  }
  lines.push('', '### Flight trajectory', '');
  for (const obs of report.observations ?? []) {
    lines.push(`- ${JSON.stringify(obs)}`);
  }
  lines.push('', '### Reproduction', '', '```bash', 'node scripts/persona-play.mjs', '```');
  lines.push('', '### Limitations', '');
  if ((report.limitations ?? []).length) {
    for (const l of report.limitations) lines.push(`- ${l}`);
  } else {
    lines.push('- No additional limitations recorded.');
  }
  lines.push('', MARKER_PREFIX + signature + ' -->');
  return lines.join('\n');
}

function existingIssue(signature, cwd) {
  try {
    const out = execFileSync('gh', ['issue', 'list', '--state', 'open', '--label', LABEL,
      '--search', `in:body "${MARKER_PREFIX}${signature}"`, '--json', 'number,title,url'],
      { encoding: 'utf8', cwd });
    const issues = JSON.parse(out);
    return issues[0] ?? null;
  } catch {
    return null;
  }
}

function ensureLabel(cwd) {
  try {
    execFileSync('gh', ['label', 'create', LABEL, '--description',
      'Auto-generated by the flight-persona skill for unnatural simulation consequences',
      '--color', 'B60205'], { encoding: 'utf8', cwd });
  } catch {
    // Label already exists or cannot be created; issue creation can still proceed.
  }
}

export async function publishAnomalyIssue(report, cwd = process.cwd()) {
  if (!report?.anomalies?.length) return { created: false, skipped: true, reason: 'no anomalies' };

  const signature = buildSignature(report);
  const existing = existingIssue(signature, cwd);
  if (existing) return { created: false, skipped: true, reason: 'duplicate', existing };

  let commit = 'unknown';
  try {
    commit = execFileSync('git', ['rev-parse', '--short', 'HEAD'], { encoding: 'utf8', cwd }).trim();
  } catch { /* keep unknown */ }

  const repoRemote = (() => {
    try {
      return execFileSync('gh', ['repo', 'view', '--json', 'nameWithOwner', '-q', '.nameWithOwner'],
        { encoding: 'utf8', cwd });
    } catch { return 'unknown'; }
  })();

  const body = formatIssue(report, { commit, repo: repoRemote });
  const dir = path.join(tmpdir(), 'flight3d-persona');
  await mkdir(dir, { recursive: true });
  const bodyFile = path.join(dir, `issue-${signature}-${Date.now()}.md`);
  await writeFile(bodyFile, body);

  ensureLabel(cwd);
  try {
    const out = execFileSync('gh', ['issue', 'create',
      '--title', `[flight-persona] ${report.mode}: ${report.anomalies[0].code} on ${report.flight?.aircraft ?? 'unknown'} @ ${report.flight?.airport ?? 'unknown'}`,
      '--label', LABEL,
      '--body-file', bodyFile], { encoding: 'utf8', cwd });
    const match = out.match(/https:\/\/github\.com\/[^\s]+/);
    return { created: true, url: match?.[0] ?? null, signature };
  } catch (error) {
    return { created: false, error: error.message, stderr: error.stderr?.toString?.() ?? null, bodyFile };
  }
}